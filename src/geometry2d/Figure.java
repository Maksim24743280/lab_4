package geometry2d; //Пакет для двумерных геометрических фигур

import java.io.Serializable; //Импортируем интерфейс Serializable для возможности сериализации

/**
 * Интерфейс двумерной геометрической фигуры.
 * Определяет общие методы: площадь и периметр.
 * Наследует Serializable, чтобы реализации можно было сохранять в бинарный файл.
 */
public interface Figure extends Serializable { //Интерфейс Figure, расширяет Serializable

    double area(); //Абстрактный метод — каждая фигура реализует свой способ расчёта площади

    double perimeter(); //Абстрактный метод — каждая фигура реализует свой способ расчёта периметра
}